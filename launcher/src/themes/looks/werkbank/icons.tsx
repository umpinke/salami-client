/** Beliebiges Pixelbild aus Zeilen (`#` = Pixel), gezeichnet in `currentColor`. */
export function PixelArt({ rows, className }: { rows: string[]; className?: string }) {
  const width = Math.max(...rows.map((row) => row.length));
  return (
    <svg
      viewBox={`0 0 ${width} ${rows.length}`}
      className={className}
      shapeRendering="crispEdges"
      aria-hidden="true"
      fill="currentColor"
    >
      {rows.flatMap((row, y) =>
        [...row].map((cell, x) => (cell === "#" ? <rect key={`${x}-${y}`} x={x} y={y} width="1" height="1" /> : null)),
      )}
    </svg>
  );
}

export function WerkbankIcon({ name, className }: { name: string; className?: string }) {
  if (hasPixelIcon(name)) return <PixelIcon name={name} className={className} />;
  return <PixelArt rows={OWN_ICONS[name] ?? OWN_ICONS.block} className={className} />;
}
