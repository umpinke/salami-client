export function hasPixelIcon(name: string): boolean {
  return name in ICONS;
}

export function PixelIcon({ name, className }: { name: string; className?: string }) {
  const rows = ICONS[name];
  if (!rows) return null;
  return (
    <svg viewBox="0 0 12 12" className={className} shapeRendering="crispEdges" aria-hidden="true" fill="currentColor">
      {rows.flatMap((row, y) =>
        [...row].map((cell, x) => (cell === "#" ? <rect key={`${x}-${y}`} x={x} y={y} width="1" height="1" /> : null)),
      )}
    </svg>
  );
}
